// ── Attribute parsers ────────────────────────────────────────────────────────

/// Read `export_to = "..."` out of ts-rs's `#[ts(...)]` attribute. Other `#[ts]`
/// keys (`export`, `rename`, `optional`, `type`, …) are skipped without error.
fn find_ts_export_to(attrs: &[syn::Attribute]) -> Option<String> {
    for attr in attrs {
        if !attr.path().is_ident("ts") {
            continue;
        }
        let mut found: Option<String> = None;
        let _ = attr.parse_nested_meta(|meta| {
            if meta.path.is_ident("export_to") {
                let value = meta.value()?;
                let s: LitStr = value.parse()?;
                found = Some(s.value());
            } else if meta.input.peek(syn::Token![=]) {
                let _ = meta
                    .value()
                    .and_then(syn::parse::ParseBuffer::parse::<Meta>);
            }
            Ok(())
        });
        if found.is_some() {
            return found;
        }
    }
    None
}

/// Re-anchor ts-rs's `export_to` so it resolves to the same final directory but
/// relative to `CARGO_MANIFEST_DIR` instead of ts-rs's `<crate>/bindings/` anchor.
/// higgs's paths are `bindings/`-relative (e.g. `"higgs/"`), so prepend `bindings/`.
fn reanchor_ts_path(ts_path: &str) -> String {
    format!("bindings/{ts_path}")
}

fn find_serde_rename_all(attrs: &[syn::Attribute]) -> Option<String> {
    for attr in attrs {
        if !attr.path().is_ident("serde") {
            continue;
        }
        let mut rename_all: Option<String> = None;
        let _ = attr.parse_nested_meta(|meta| {
            if meta.path.is_ident("rename_all") {
                let value = meta.value()?;
                let s: LitStr = value.parse()?;
                rename_all = Some(s.value());
            } else {
                let _ = meta
                    .value()
                    .and_then(syn::parse::ParseBuffer::parse::<Meta>);
            }
            Ok(())
        });
        if rename_all.is_some() {
            return rename_all;
        }
    }
    None
}

fn find_serde_rename(attrs: &[syn::Attribute]) -> Option<String> {
    for attr in attrs {
        if !attr.path().is_ident("serde") {
            continue;
        }
        let mut rename: Option<String> = None;
        let _ = attr.parse_nested_meta(|meta| {
            if meta.path.is_ident("rename") {
                let value = meta.value()?;
                let s: LitStr = value.parse()?;
                rename = Some(s.value());
            } else {
                let _ = meta
                    .value()
                    .and_then(syn::parse::ParseBuffer::parse::<Meta>);
            }
            Ok(())
        });
        if rename.is_some() {
            return rename;
        }
    }
    None
}

// ── Case conversion (matches serde's rename_all rules) ────────────────────────

fn apply_rename_all(name: &str, rule: Option<&str>) -> String {
    match rule {
        None | Some("PascalCase") => name.to_string(),
        Some("lowercase") => name.to_lowercase(),
        Some("UPPERCASE") => name.to_uppercase(),
        Some("camelCase") => to_camel_case(name),
        Some("snake_case") => to_snake_case(name),
        Some("SCREAMING_SNAKE_CASE") => to_snake_case(name).to_uppercase(),
        Some("kebab-case") => to_snake_case(name).replace('_', "-"),
        Some("SCREAMING-KEBAB-CASE") => to_snake_case(name).replace('_', "-").to_uppercase(),
        Some(_) => name.to_string(),
    }
}

/// Apply a serde container `rename_all` rule to a STRUCT FIELD identifier,
/// mirroring serde's `RenameRule::apply_to_field`. Distinct from
/// [`apply_rename_all`], which targets PascalCase enum VARIANTS — struct fields
/// are snake_case at the source, so the word boundaries (and thus the camelCase/
/// PascalCase conversions) differ. Used so [`TsParamHelp`](derive_ts_param_help)
/// keys match the serialized/ts-rs wire names under a container rename.
/// Apply serde's container `rename_all` rule to a PascalCase VARIANT ident
/// (the variant analogue of [`apply_rename_all_field`]; serde leaves variants
/// untouched without a rule).
fn apply_rename_all_variant(variant: &str, rule: Option<&str>) -> String {
    match rule {
        None | Some("PascalCase") => variant.to_string(),
        Some("lowercase") => variant.to_lowercase(),
        Some("UPPERCASE") => variant.to_uppercase(),
        Some("snake_case") => pascal_to_snake(variant),
        Some("SCREAMING_SNAKE_CASE") => pascal_to_snake(variant).to_uppercase(),
        Some("camelCase") => {
            let mut c = variant.chars();
            match c.next() {
                Some(f) => f.to_lowercase().collect::<String>() + c.as_str(),
                None => String::new(),
            }
        }
        Some(other) => panic!("TsParamHelp: unsupported rename_all rule {other:?}"),
    }
}

/// `PascalCase` → `snake_case` (serde's variant snake_case rule).
fn pascal_to_snake(s: &str) -> String {
    let mut out = String::new();
    for (i, ch) in s.chars().enumerate() {
        if ch.is_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.extend(ch.to_lowercase());
        } else {
            out.push(ch);
        }
    }
    out
}

fn apply_rename_all_field(field: &str, rule: Option<&str>) -> String {
    match rule {
        // serde leaves snake_case fields untouched for None/lowercase/snake_case.
        None | Some("lowercase") | Some("snake_case") => field.to_string(),
        Some("UPPERCASE") | Some("SCREAMING_SNAKE_CASE") => field.to_uppercase(),
        Some("PascalCase") => field_to_pascal(field),
        Some("camelCase") => {
            let pascal = field_to_pascal(field);
            let mut chars = pascal.chars();
            match chars.next() {
                None => String::new(),
                Some(c) => c.to_lowercase().chain(chars).collect(),
            }
        }
        Some("kebab-case") => field.replace('_', "-"),
        Some("SCREAMING-KEBAB-CASE") => field.to_uppercase().replace('_', "-"),
        Some(_) => field.to_string(),
    }
}

/// Convert a snake_case field identifier to PascalCase (`ctx_len` → `CtxLen`),
/// matching serde's field PascalCase rule (capitalize each `_`-separated word).
fn field_to_pascal(field: &str) -> String {
    let mut out = String::with_capacity(field.len());
    let mut capitalize = true;
    for ch in field.chars() {
        if ch == '_' {
            capitalize = true;
        } else if capitalize {
            out.extend(ch.to_uppercase());
            capitalize = false;
        } else {
            out.push(ch);
        }
    }
    out
}

fn to_snake_case(pascal: &str) -> String {
    let mut out = String::with_capacity(pascal.len() + 4);
    for (i, ch) in pascal.chars().enumerate() {
        if ch.is_uppercase() {
            if i != 0 {
                out.push('_');
            }
            for lower in ch.to_lowercase() {
                out.push(lower);
            }
        } else {
            out.push(ch);
        }
    }
    out
}

fn to_camel_case(pascal: &str) -> String {
    let mut chars = pascal.chars();
    match chars.next() {
        None => String::new(),
        Some(c) => c.to_lowercase().chain(chars).collect(),
    }
}
